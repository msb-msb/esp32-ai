# Bench prompt source: plain TinyStories-style prose, long enough for 128+
# tokens. It starts "Once upon a time" so the 4-token prompt is the compiled
# benchmark prompt (433 447 259 405).
BENCH_TEXT = (
    "Once upon a time, there was a small dog named Max who lived in a yellow house "
    "near the park. Every morning, Max ran to the window to watch the birds eat "
    "seeds from the feeder. One day, a big gray cat came into the yard and the "
    "birds flew away. Max was sad because he liked the birds very much. He barked "
    "at the cat, but the cat did not move. Then Max had an idea. He took his red "
    "ball and rolled it across the grass. The cat saw the ball and ran after it, "
    "all the way out of the yard. The next morning, the birds came back to the "
    "feeder. Max wagged his tail and watched them sing. His friend Lily, the girl "
    "who lived next door, came over to play. She threw the ball for Max and they "
    "laughed and ran until the sun went down. That night, Max slept in his warm "
    "bed and dreamed about birds, balls and his best friend."
)


class Board:
    def __init__(self, port, reset=False, log=None):
        # Opening the USB-Serial/JTAG port leaves DTR/RTS asserted together,
        # which does not reset the chip; --reset does the RTS pulse that
        # capture_serial.py uses, then waits for the boot's R line.
        self.s = serial.Serial(port, 115200, timeout=0.05)
        self.log = open(log, "ab") if log else None
        self.buf = b""
        self.ready = None
        if reset:
            self.s.dtr = False; self.s.rts = True; time.sleep(0.1); self.s.rts = False
            self.wait_ready(120.0, ping=False)
        else:
            self.wait_ready(10.0, ping=True)

    def _log(self, direction, line):
        if self.log:
            self.log.write(b"%.6f %s %s\n" % (time.time(), direction, line))
            self.log.flush()

    def readline(self, timeout):
        """Next line (bytes, without newline) or None on timeout."""
        t0 = time.time()
        while b"\n" not in self.buf:
            if time.time() - t0 > timeout:
                return None
            try:
                chunk = self.s.read(4096)
            except serial.SerialException:
                # the port re-enumerates after a reset; reopen
                time.sleep(0.2)
                try:
                    self.s.close(); self.s.open()
                except Exception:
                    pass
                continue
            self.buf += chunk
        line, self.buf = self.buf.split(b"\n", 1)
        line = line.rstrip(b"\r")
        self._log(b"<", line)
        return line

    def send(self, line):
        self._log(b">", line.encode())
        self.s.write(line.encode() + b"\n")
        self.s.flush()

    def wait_ready(self, timeout, ping):
        if ping:
            self.s.reset_input_buffer()
            self.send("?")
        t0 = time.time()
        while time.time() - t0 < timeout:
            line = self.readline(timeout - (time.time() - t0))
            if line is None:
                break
            if line.startswith(b"R ready"):
                self.ready = line.decode()
                return
            if line.startswith(b"FATAL"):
                raise SystemExit(f"board: {line.decode()}")
        raise SystemExit("board did not answer with an R line; is INTERACTIVE=1 "
                         "firmware flashed? (try --reset)")

    def generate(self, ids, n, temp, top_p, seed, eot, on_token=None, timeout=120.0):
        """Send P + G, return dict with ids, D fields, H lines and host timings."""
        self.send("P " + " ".join(map(str, ids)))
        t_send = time.time()
        self.send(f"G n={n} t={temp:g} p={top_p:g} s={seed} eot={int(eot)}")
        out, hashes, t_first = [], {}, None
        while True:
            line = self.readline(timeout)
            if line is None:
                raise SystemExit("timeout waiting for the board")
            if line.startswith(b"T "):
                tok = int(line[2:])
                if t_first is None:
                    t_first = time.time()
                out.append(tok)
                if on_token:
                    on_token(tok)
            elif line.startswith(b"D "):
                t_end = time.time()
                d = dict(kv.split("=") for kv in line[2:].decode().split())
                break
            elif line.startswith(b"E "):
                raise SystemExit(f"board error: {line[2:].decode()}")
            # anything else (IDF log lines) is ignored
        # LOGIT_CHECKSUM builds follow D with H lines ending in "H all".
        if self.ready and "checksum=1" in self.ready:
            while True:
                line = self.readline(5.0)
                if line is None:
                    break
                m = re.match(rb"H (\S+) ([0-9a-f]{16})", line)
                if m:
                    hashes[m.group(1).decode()] = m.group(2).decode()
                    if m.group(1) == b"all":
                        break
        return {
            "ids": out,
            "ttft_us": int(d["ttft_us"]),
            "decode_ms_per_tok": float(d["decode_ms_per_tok"]),
            "n": int(d["n"]),
            "hashes": hashes,
            "host_ttft_ms": (t_first - t_send) * 1e3 if t_first else None,
            "host_total_ms": (t_end - t_send) * 1e3,
            "host_stream_tok_s": ((len(out) - 1) / (t_end - t_first)
                                  if t_first and len(out) > 1 else None),
        }


class Codec:
    def __init__(self, path):
        self.tok = Tokenizer.from_file(path)
        # Same per-token bytes as generated/vocab.h (generate_vocab.py).
        self.cache = {}

    def encode(self, text):
        return self.tok.encode(text).ids

    def piece(self, i):
        b = self.cache.get(i)
        if b is None:
            b = self.cache[i] = self.tok.decode([i]).encode("utf-8")
        return b


def parse_ids(s):
    return [int(x) for x in s.replace(",", " ").split()]


def text_sha(codec, prompt_ids, gen_ids):
    blob = b">>> " + b"".join(codec.piece(i) for i in prompt_ids) + \
           b"".join(codec.piece(i) for i in gen_ids)
    return hashlib.sha256(blob).hexdigest(), len(blob)


def stats_line(r):
    ms = r["decode_ms_per_tok"]
    # forward = the board's llm_forward time only (the benchmark's ms/token);
    # stream = tokens arriving at the host, which includes sampling.
    host = (f" | stream {r['host_stream_tok_s']:.2f} tok/s"
            if r["host_stream_tok_s"] else "")
    return (f"[TTFT {r['ttft_us'] / 1e3:.1f} ms | forward {ms:.2f} ms/token, "
            f"{1e3 / ms if ms else 0:.2f} tok/s | {r['n']} tokens{host}]")


def one_reply(board, codec, args, prompt_ids, seed, show_ids=False):
    out = sys.stdout.buffer
    if not show_ids:
        out.write(b"".join(codec.piece(i) for i in prompt_ids))
        out.flush()

    def on_token(t):
        out.write(f"{t} ".encode() if show_ids else codec.piece(t))
        out.flush()

    r = board.generate(prompt_ids, args.n, args.temp, args.top_p, seed, args.eot, on_token)
    print("\n" + stats_line(r) + (f" seed={seed}" if args.temp > 0 else ""))
    return r


def run_bench(board, codec, args):
    if args.raw_ids and args.prompt:
        base = parse_ids(args.prompt)
    else:
        text = (open(args.bench_text).read() if args.bench_text
                else args.prompt if args.prompt else BENCH_TEXT)
        base = codec.encode(text)
    lengths = [int(x) for x in args.lengths.split(",")]
    seeds = [int(x) for x in args.seeds.split(",")]
    if max(lengths) > len(base):
        raise SystemExit(f"bench text is {len(base)} tokens, need {max(lengths)}")
    fields = ["label", "prompt_len", "seed", "run", "n_req", "temp", "top_p", "eot",
              "ttft_us", "decode_ms_per_tok", "n", "host_ttft_ms", "host_total_ms",
              "out_ids_sha256", "text_sha256", "logit_hash_all", "prompt_ids_sha256"]
    new = not os.path.exists(args.csv)
    with open(args.csv, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        if new:
            w.writeheader()
        for L in lengths:
            ids = base[:L]
            for seed in seeds:
                for run in range(1, args.runs + 1):
                    r = board.generate(ids, args.bench_n, args.temp, args.top_p, seed, args.eot)
                    tsha, _ = text_sha(codec, ids, r["ids"])
                    row = {
                        "label": args.label, "prompt_len": L, "seed": seed, "run": run,
                        "n_req": args.bench_n, "temp": args.temp, "top_p": args.top_p,
                        "eot": int(args.eot), "ttft_us": r["ttft_us"],
                        "decode_ms_per_tok": r["decode_ms_per_tok"], "n": r["n"],
                        "host_ttft_ms": f"{r['host_ttft_ms']:.1f}" if r["host_ttft_ms"] else "",
                        "host_total_ms": f"{r['host_total_ms']:.1f}",
                        "out_ids_sha256": hashlib.sha256(
                            " ".join(map(str, r["ids"])).encode()).hexdigest(),
                        "text_sha256": tsha,
                        "logit_hash_all": r["hashes"].get("all", ""),
                        "prompt_ids_sha256": hashlib.sha256(
                            " ".join(map(str, ids)).encode()).hexdigest(),
                    }
                    w.writerow(row); f.flush()
                    print(f"{args.label} len={L:4d} seed={seed} run={run} "
                          f"ttft={r['ttft_us'] / 1e3:8.1f} ms  "
                          f"decode={r['decode_ms_per_tok']:.3f} ms/tok  n={r['n']}  "
                          f"out={row['out_ids_sha256'][:12]}", flush=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--port", default="/dev/ttyACM0")
    ap.add_argument("--tokenizer", default=DEFAULT_TOK)
    ap.add_argument("--temp", type=float, default=0.8, help="0 = greedy (argmax)")
    ap.add_argument("--top-p", type=float, default=0.9)
    ap.add_argument("--seed", type=int, default=None,
                    help="fixed sampling seed; default: a new random seed per reply")
    ap.add_argument("--n", type=int, default=200, help="max tokens per reply")
    ap.add_argument("--eot", type=int, default=1, choices=[0, 1],
                    help="1 = stop at <|endoftext|>")
    ap.add_argument("--raw-ids", action="store_true",
                    help="prompts are token ids; replies print as ids")
    ap.add_argument("--prompt", help="one-shot prompt (or bench source) instead of stdin")
    ap.add_argument("--log", help="append every serial line, timestamped, to this file")
    ap.add_argument("--reset", action="store_true", help="reset the board first")
    ap.add_argument("--bench", action="store_true")
    ap.add_argument("--csv", default="chat-bench.csv")
    ap.add_argument("--lengths", default="4,16,64,128")
    ap.add_argument("--runs", type=int, default=3)
    ap.add_argument("--bench-n", type=int, default=32)
    ap.add_argument("--seeds", default="0")
    ap.add_argument("--label", default="bench")
    ap.add_argument("--bench-text")
    args = ap.parse_args()

    codec = Codec(args.tokenizer)
    board = Board(args.port, reset=args.reset, log=args.log)
    print(board.ready, file=sys.stderr)

    if args.bench:
        run_bench(board, codec, args)
        return

    def ids_of(s):
        return parse_ids(s) if args.raw_ids else codec.encode(s)

    if args.prompt is not None:
        ids = ids_of(args.prompt)
        seed = args.seed if args.seed is not None else random.randrange(2**32)
        r = one_reply(board, codec, args, ids, seed, show_ids=args.raw_ids)
        tsha, tlen = text_sha(codec, ids, r["ids"])
        print(f"prompt ids: {' '.join(map(str, ids))}")
        print(f"text sha256 {tsha} ({tlen} B)")
        if r["hashes"]:
            print(f"logit_hash_all {r['hashes'].get('all')}")
        return

    print("Type a story opening and press Enter (Ctrl-D to quit).", file=sys.stderr)
    for line in sys.stdin:
        line = line.rstrip("\n")
        if not line.strip():
            continue
        ids = ids_of(line)
        if not ids:
            continue
        seed = args.seed if args.seed is not None else random.randrange(2**32)
        try:
            one_reply(board, codec, args, ids, seed, show_ids=args.raw_ids)
        except SystemExit as e:
            print(e, file=sys.stderr)


if __name__ == "__main__":
    main()
