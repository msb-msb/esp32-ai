"""Chat with the ESP32-S3 TinyStories board in INTERACTIVE=1 firmware.

usage (repo venv, for its tokenizers):
  uv run --no-project --with pyserial --with tokenizers==0.23.1 \
    python scripts/insiderllm/chat.py [--port /dev/ttyACM0] [--temp 0.8]
      [--top-p 0.9] [--seed N] [--n 200] [--eot 1] [--raw-ids] [--prompt TEXT]
      [--log FILE] [--reset]
  ... scripts/insiderllm/chat.py --bench --csv out.csv [--lengths 4,16,64,128] [--runs 3]
      [--bench-n 32] [--seeds 0] [--label X] [--bench-text FILE | --prompt TEXT]

Without --prompt it reads prompts from stdin, one per line, and streams each
reply. --raw-ids takes prompts as space-separated token ids instead of text.
Each prompt is one-shot: the board resets its KV cache for every P line.

Protocol (INTERACTIVE=1 firmware, firmware/esp32_tinystories):
  host -> board  "P <id> ...", "G n= t= p= s= eot=", "?"
  board -> host  "T <id>" per token, "D ttft_us= decode_ms_per_tok= n=",
                 "R ready ...", "E <reason>", and "H .." logit hashes in
                 LOGIT_CHECKSUM builds.

--bench sends a fixed prompt list: the bench text (built in, or --bench-text /
--prompt) tokenized and cut to each of --lengths tokens, each run --runs times
per seed, and writes one CSV row per run. text_sha256 is sha256 of
">>> " + prompt bytes + generated bytes, the span parse_run.py hashes.

pyserial is not in the repo venv; if it is missing, the copy that ships with
an esptool uv tool install is put on sys.path (pure Python).
"""
